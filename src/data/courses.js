export function getCourseBySlug(slug) {
  return courses.find((c) => c.slug === slug || c.id === slug);
}

export function getRelatedCourses(course, limit = 3) {
  return courses
    .filter((c) => c.id !== course.id && c.category === course.category)
    .slice(0, limit);
}

